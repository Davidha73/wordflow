/**
 * Hydrates all `[data-lucide]` placeholders within the given root element.
 * Safe to call repeatedly after dynamic DOM renders.
 */
export function initIcons(root = document) {
  createIcons({
    icons: APP_ICONS,
    attrs: {
      'aria-hidden': 'true',
      'stroke-width': 1.85,
    },
    root,
  });
}

/**
 * Creates a `<i data-lucide="...">` placeholder element for dynamic templates.
 */
export function createIconPlaceholder(name, className = '') {
  const el = document.createElement('i');
  el.setAttribute('data-lucide', name);
  if (className) {
    el.className = className;
  }
  return el;
}
